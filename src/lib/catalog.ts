// Each sample color has an independently addressable variant. Existing IDs remain stable.
export const products: Product[] = seedProducts.map(product => ({...product,
  origin: 'Sample product; country of manufacture not verified.',
  variants: product.colors.map(color => product.variants.find(v=>v.color===color.name) ?? {
    ...product.variants[0], color:color.name,
    id: `${product.variants[0].id}_${color.name.toLowerCase().replace(/[^a-z0-9]+/g,'_')}` as VariantId,
    sku:`${product.styleCode}-${color.name.toUpperCase()}`,
  }),
}));

export const formatMoney = (money: Product["price"], locale = "en-US") =>
  new Intl.NumberFormat(locale, { style: "currency", currency: money.currency }).format(money.amount / 100);

export const findProduct = (slug: string) => products.find((item) => item.slug === slug);

export const getProductsByCategory = (category: ProductCategory) =>
  products.filter((item) => item.category === category);

export const getProductsByAudience = (audience: Product["audience"][number]) =>
  products.filter((item) => item.audience.includes(audience));
